#!/usr/bin/env bash
# Install dsh-native-tui into a DSH profile. The profile is initialized by
# dsh on first use; the default profile is "tui".
set -euo pipefail

profile='tui'
mode='link'
build=1
command_name=''
install_command=1

usage() {
  cat <<'EOF'
Usage: scripts/install.sh [options]

Install dsh-native-tui into a DSH profile.

Options:
  -p, --profile <name>  DSH profile to install into (default: tui)
      --pack            install a packed tarball from .tmp instead of linking
                        this checkout; a previous installation is removed first
                        so an unchanged version still picks up the rebuilt tgz
      --no-build        skip pnpm install/build (requires an existing dist/)
      --command <name>  launcher command name (default: dnt for tui, dnt-<profile> otherwise)
  -h, --help            show this help

Environment:
  DSH_HOME              DSH home used by dsh (dsh's own default when unset)
  DSH_NATIVE_TUI_NO_LAUNCHER=1
                        skip the launcher command

Examples:
  scripts/install.sh
  scripts/install.sh --profile work
  scripts/install.sh --profile work --command work-tui
EOF
}

die() {
  echo "install: $*" >&2
  exit 1
}

while (($# > 0)); do
  case "$1" in
    -p|--profile)
      (($# >= 2)) || die "missing value for $1"
      profile="$2"
      shift 2
      ;;
    --pack)
      mode='pack'
      shift
      ;;
    --no-build)
      build=0
      shift
      ;;
    --command)
      (($# >= 2)) || die "missing value for $1"
      command_name="$2"
      install_command=1
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      die "unknown option: $1"
      ;;
  esac
done

[[ -n "$profile" ]] || die "profile must not be empty"
command -v pnpm >/dev/null 2>&1 || die "pnpm is required (https://pnpm.io)"
command -v dsh >/dev/null 2>&1 || die "dsh is required but was not found on PATH"
if [[ "${DSH_NATIVE_TUI_NO_LAUNCHER:-}" == '1' ]]; then
  install_command=0
fi

if ((install_command)); then
  [[ "$profile" =~ ^[A-Za-z0-9._-]+$ ]] || die "profile name is not safe for a launcher: $profile"
  # Keep the default name in sync with launcherName() in src/runtime/launcher.ts.
  if [[ -z "$command_name" ]]; then
    command_name='dnt'
    [[ "$profile" == 'tui' ]] || command_name="dnt-$profile"
  fi
  [[ "$command_name" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || die "invalid command name: $command_name"
  bin_dir="${XDG_BIN_HOME:-$HOME/.local/bin}"
  [[ "$bin_dir" == /* ]] || die "XDG_BIN_HOME must be an absolute path: $bin_dir"
  command_path="$bin_dir/$command_name"
  if [[ -e "$command_path" ]] && { [[ ! -f "$command_path" ]] || ! grep -qF '# dsh-native-tui launcher' "$command_path"; }; then
    die "$command_path already exists and was not created by dsh-native-tui; remove it or set DSH_NATIVE_TUI_NO_LAUNCHER=1"
  fi
fi

install_launcher() {
  # Keep the generated text in sync with launcherScript() in src/runtime/launcher.ts.
  mkdir -p "$bin_dir"
  cat >"$command_path" <<EOF
#!/bin/sh
# dsh-native-tui launcher: run the "$profile" profile.
# Generated by dsh-native-tui; remove this file to remove the command.
exec dsh --profile '$profile' "\$@"
EOF
  chmod 755 "$command_path"
  echo "==> installed $command_name -> $command_path"
}

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

if ((build)); then
  echo "==> pnpm install --frozen-lockfile"
  pnpm install --frozen-lockfile
  echo "==> pnpm build"
  pnpm build
else
  [[ -f dist/index.js ]] || die "dist/index.js is missing; run without --no-build"
fi

if [[ "$mode" == 'pack' ]]; then
  mkdir -p .tmp
  echo "==> pnpm pack"
  pack_json="$(pnpm pack --pack-destination .tmp --json)"
  target="$(printf '%s' "$pack_json" | node -e 'let s = ""; process.stdin.on("data", d => { s += d }); process.stdin.on("end", () => { try { process.stdout.write(JSON.parse(s).filename ?? "") } catch {} })')"
  [[ -n "$target" ]] || die "could not read the packed tarball path from pnpm pack"
  # pnpm skips resolution when the profile lockfile already pins the same
  # tarball path and version, so a rebuilt tarball would otherwise stay stale.
  if dsh plugin --profile "$profile" remove dsh-native-tui >/dev/null 2>&1; then
    echo "==> removed the previous installation"
  fi
  echo "==> dsh plugin --profile $profile add $target"
  dsh plugin --profile "$profile" add "$target"
else
  echo "==> dsh plugin --profile $profile add $repo_root"
  dsh plugin --profile "$profile" add "$repo_root"
fi

if ((install_command)); then
  install_launcher
  case ":$PATH:" in
    *":$bin_dir:"*) ;;
    *) echo "note: $bin_dir is not on PATH; add it to run \"$command_name\"." ;;
  esac
fi

echo
echo "Installed dsh-native-tui into profile \"$profile\"."
echo "Start it with:"
if ((install_command)); then
  echo "  $command_name"
  echo "  (or: dsh --profile $profile)"
else
  echo "  dsh --profile $profile"
fi
