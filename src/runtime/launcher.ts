import { chmod, mkdir, open, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { basename, isAbsolute, join, resolve } from 'node:path'

/** Marker shared with scripts/install.sh; keep both in sync. */
export const LAUNCHER_MARKER = '# dsh-native-tui launcher'

const SAFE_PROFILE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/

/** Outcome of one launcher reconciliation. */
export interface LauncherOutcome {
  readonly status: 'created' | 'current' | 'skipped'
  readonly path?: string
  readonly reason?: string
}

/**
 * Read the profile name from the dsh launcher arguments.
 * DSH accepts both `dsh --profile tui` and the shorthand `dsh tui`.
 * @param argv - arguments after the node executable and bin script.
 * @returns the profile name, or undefined when the invocation has none.
 */
export function parseProfileArg(argv: readonly string[]): string | undefined {
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === undefined) continue
    if (arg === '--profile') {
      const value = argv[index + 1]
      return value === undefined || value === '' || value.startsWith('-') ? undefined : value
    }
    if (arg.startsWith('--profile=')) {
      const value = arg.slice('--profile='.length)
      return value === '' ? undefined : value
    }
  }
  const first = argv[0]
  return first !== undefined && !first.startsWith('-') && first !== 'plugin' ? first : undefined
}

/**
 * Pick the launcher name for a profile. The default tui profile owns `dnt`;
 * other profiles get a suffix so two profiles never overwrite each other.
 * @param profile - DSH profile name.
 * @returns the command name without a directory.
 */
export function launcherName(profile: string): string {
  return profile === 'tui' ? 'dnt' : `dnt-${profile}`
}

/**
 * Render the launcher script.
 * @param profile - validated DSH profile name.
 * @returns a POSIX shell script that forwards every argument to dsh.
 */
export function launcherScript(profile: string): string {
  return [
    '#!/bin/sh',
    `${LAUNCHER_MARKER}: run the "${profile}" profile.`,
    '# Generated by dsh-native-tui; remove this file to remove the command.',
    `exec dsh --profile '${profile}' "$@"`,
    '',
  ].join('\n')
}

/**
 * Resolve the directory that holds user commands.
 * @param env - environment to read `XDG_BIN_HOME` and `HOME` from.
 * @returns an absolute directory, or undefined for a relative XDG override.
 */
export function resolveLauncherDir(env: NodeJS.ProcessEnv = process.env): string | undefined {
  const configured = env.XDG_BIN_HOME
  if (configured !== undefined && configured !== '') {
    return isAbsolute(configured) ? configured : undefined
  }
  const home = env.HOME ?? homedir()
  return isAbsolute(home) ? join(home, '.local', 'bin') : undefined
}

/**
 * Runtime creation is for the normal installed home. Test and probe runs point
 * DSH_HOME at a throwaway directory, and must not write commands into the real
 * user's bin directory for a profile that will disappear with that directory.
 * @param env - environment to read `DSH_HOME` and `HOME` from.
 * @returns true when runtime creation is safe for this home.
 */
function usesDefaultHome(env: NodeJS.ProcessEnv): boolean {
  const configured = env.DSH_HOME
  if (configured === undefined || configured.trim() === '') return true
  return resolve(configured) === join(env.HOME ?? homedir(), '.dsh')
}

/**
 * Find an existing dsh-native-tui launcher for one profile under any name.
 * @param dir - command directory.
 * @param profile - profile whose marker is searched for.
 * @param exclude - path already handled by the caller.
 * @returns the matching launcher path, or undefined.
 */
async function findProfileLauncher(dir: string, profile: string, exclude: string): Promise<string | undefined> {
  const marker = `${LAUNCHER_MARKER}: run the "${profile}" profile.`
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => undefined)
  if (entries === undefined) return undefined
  for (const entry of entries) {
    if (!entry.isFile()) continue
    const path = join(dir, entry.name)
    if (path === exclude) continue
    try {
      const handle = await open(path, 'r')
      try {
        const buffer = Buffer.alloc(512)
        const { bytesRead } = await handle.read(buffer, 0, buffer.length, 0)
        if (buffer.toString('utf8', 0, bytesRead).includes(marker)) return path
      } finally {
        await handle.close()
      }
    } catch {
      // A command may be unreadable or binary; it is not ours.
    }
  }
  return undefined
}

/**
 * Find the launcher that currently serves one profile without creating one.
 * @param profile - parsed profile name.
 * @param env - environment to read paths from.
 * @returns the launcher path, or undefined when none belongs to this profile.
 */
export async function findLauncher(profile: string | undefined, env: NodeJS.ProcessEnv = process.env): Promise<string | undefined> {
  if (profile === undefined || !SAFE_PROFILE.test(profile)) return undefined
  const dir = resolveLauncherDir(env)
  if (dir === undefined) return undefined
  const path = join(dir, launcherName(profile))
  const marker = `${LAUNCHER_MARKER}: run the "${profile}" profile.`
  try {
    const text = await readFile(path, 'utf8')
    if (text.includes(marker)) return path
  } catch {
    // Fall through to a custom-named launcher.
  }
  return findProfileLauncher(dir, profile, path)
}

/**
 * Format the resume command printed after the TUI exits. Prefer the installed
 * launcher when one belongs to this profile; otherwise fall back to dsh.
 * @param profile - parsed profile name.
 * @param launcher - launcher path found for this profile.
 * @param sessionId - Session to resume.
 * @returns a shell command without a trailing newline.
 */
export function resumeHint(profile: string | undefined, launcher: string | undefined, sessionId: string): string {
  const name = profile !== undefined && SAFE_PROFILE.test(profile) ? profile : 'tui'
  const command = launcher === undefined ? `dsh --profile ${name}` : basename(launcher)
  return `${command} --resume ${sessionId}`
}

/**
 * Create or refresh the launcher for one profile without touching foreign
 * commands. A file is only replaced when it carries this package's marker.
 * @param profile - parsed profile name, or undefined when the host did not pass one.
 * @param env - environment to read paths and opt-outs from.
 * @returns what happened, for diagnostics.
 */
export async function ensureLauncher(profile: string | undefined, env: NodeJS.ProcessEnv = process.env): Promise<LauncherOutcome> {
  if (profile === undefined) return { status: 'skipped', reason: 'no profile argument' }
  if (!SAFE_PROFILE.test(profile)) return { status: 'skipped', reason: 'unsafe profile name' }
  if (env.DSH_NATIVE_TUI_NO_LAUNCHER === '1') return { status: 'skipped', reason: 'disabled by DSH_NATIVE_TUI_NO_LAUNCHER' }
  if (!usesDefaultHome(env)) return { status: 'skipped', reason: 'non-default DSH_HOME' }

  const dir = resolveLauncherDir(env)
  if (dir === undefined) return { status: 'skipped', reason: 'XDG_BIN_HOME must be absolute' }

  const path = join(dir, launcherName(profile))
  const content = launcherScript(profile)
  let existing: string | undefined
  try {
    existing = await readFile(path, 'utf8')
  } catch {
    existing = undefined
  }

  if (existing !== undefined && !existing.includes(LAUNCHER_MARKER)) {
    const other = await findProfileLauncher(dir, profile, path)
    return other === undefined
      ? { status: 'skipped', path, reason: 'foreign file' }
      : { status: 'current', path: other }
  }
  if (existing === content) return { status: 'current', path }
  const other = await findProfileLauncher(dir, profile, path)
  if (other !== undefined) return { status: 'current', path: other }

  await mkdir(dir, { recursive: true })
  const temporary = join(dir, `.${launcherName(profile)}.${process.pid}.tmp`)
  try {
    await writeFile(temporary, content, { mode: 0o755 })
    await chmod(temporary, 0o755)
    await rename(temporary, path)
  } finally {
    await rm(temporary, { force: true }).catch(() => undefined)
  }
  return { status: 'created', path }
}
